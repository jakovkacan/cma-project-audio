import numpy as np
from scipy.signal import stft


def make_music(seed, fs=8000, seconds=6):
    """
    Synthesizes a short harmonic audio scene with randomized note timing,
    amplitude envelopes, harmonic phases, and low-level noise. The generated
    signal is analyzed with a Hann-windowed short-time Fourier transform, and
    note activity is aligned to the resulting analysis frames. Unchanged code
    provided from the project specification document.

    :param seed: Seed or random generator input used to initialize the random
        number generator.
    :type seed: int or sequence of int or numpy.random.SeedSequence or
        numpy.random.BitGenerator or numpy.random.Generator or None
    :param fs: Sampling frequency used for synthesis and spectral analysis.
    :type fs: int or float
    :param seconds: Duration of the synthesized signal.
    :type seconds: int or float
    :return: Tuple containing the magnitude spectrogram, frame-aligned note
        activity mask, frequency bins, and frame times.
    :rtype: tuple[numpy.ndarray, numpy.ndarray, numpy.ndarray, numpy.ndarray]
    :raises TypeError: If an input cannot be interpreted as the required
        random generator input or numeric value.
    :raises ValueError: If the sampling configuration or generated signal length
        is invalid for synthesis or spectral analysis.
    """  # Docstring generated by Junie LLM

    rng = np.random.default_rng(seed)
    time = np.arange(int(fs * seconds)) / fs
    pitches = [220.0, 277.18, 329.63]
    audio = np.zeros_like(time)
    active = np.zeros((3, len(time)), dtype=bool)

    for k, f0 in enumerate(pitches):
        starts = [0.2 + 0.8 * k, rng.uniform(3.0, 4.8)]
        for start in starts:
            duration = rng.uniform(0.35, 0.65)
            age = time - start
            on = (age >= 0) & (age < duration)
            envelope = np.zeros_like(time)
            envelope[on] = (
                    (1 - np.exp(-age[on] / 0.02))
                    * np.exp(-age[on] / 0.5))
            tone = np.zeros_like(time)
            for harmonic in range(1, 7):
                frequency = harmonic * f0
                if frequency < fs / 2:
                    phase = rng.uniform(0, 2 * np.pi)
                    tone += np.sin(
                        2 * np.pi * frequency * time + phase
                    ) / harmonic
            audio += envelope * tone
            active[k] |= on

    audio += 0.005 * rng.normal(size=len(time))
    freq, frames, Z = stft(
        audio, fs=fs, window="hann", nperseg=512,
        noverlap=384, boundary=None, padded=False)
    indices = np.rint(frames * fs).astype(int)
    return np.abs(Z), active[:, indices], freq, frames


def make_clip(seed, noise_std=0.005, fs=8000, seconds=6):
    """
    Generate a synthetic audio clip containing short harmonic tones, additive
    Gaussian noise, frame-aligned activity targets, and a short-time Fourier
    transform magnitude representation.

    :param seed: Seed used to initialize the random number generator that controls
        tone timing, duration, phase, and noise.
    :type seed: int or sequence of int or numpy.random.SeedSequence or
        numpy.random.BitGenerator or numpy.random.Generator or None
    :param noise_std: Standard deviation of the additive Gaussian noise.
    :type noise_std: float
    :param fs: Sampling frequency in hertz.
    :type fs: int
    :param seconds: Duration of the generated clip in seconds.
    :type seconds: float
    :raises ValueError: If ``noise_std`` is not positive and finite.
    :return: Dictionary containing the magnitude spectrogram, frame-aligned
        activity matrix, frequency bins, frame times, seed, and noise standard
        deviation.
    :rtype: dict[str, object]
    """  # Docstring generated by Junie LLM

    if not np.isfinite(noise_std) or noise_std <= 0:
        raise ValueError("noise_std must be positive and finite.")

    rng = np.random.default_rng(seed)
    time = np.arange(int(fs * seconds)) / fs
    pitches = [220.0, 277.18, 329.63]
    audio = np.zeros_like(time)
    active = np.zeros((3, len(time)), dtype=bool)

    for k, f0 in enumerate(pitches):
        starts = [0.2 + 0.8 * k, rng.uniform(3.0, 4.8)]
        for start in starts:
            duration = rng.uniform(0.35, 0.65)
            age = time - start
            on = (age >= 0) & (age < duration)
            envelope = np.zeros_like(time)
            envelope[on] = (
                    (1 - np.exp(-age[on] / 0.02))
                    * np.exp(-age[on] / 0.5))
            tone = np.zeros_like(time)
            for harmonic in range(1, 7):
                frequency = harmonic * f0
                if frequency < fs / 2:
                    phase = rng.uniform(0, 2 * np.pi)
                    tone += np.sin(
                        2 * np.pi * frequency * time + phase
                    ) / harmonic
            audio += envelope * tone
            active[k] |= on

    audio += noise_std * rng.normal(size=len(time))
    freq, frames, Z = stft(
        audio, fs=fs, window="hann", nperseg=512,
        noverlap=384, boundary=None, padded=False)
    indices = np.rint(frames * fs).astype(int)

    return {
        "V": np.abs(Z),
        "Y": active[:, indices],
        "freq": freq,
        "times": frames,
        "seed": seed,
        "noise_std": noise_std
    }


# {"dev": [0, 10], "val": [100, 110], "test": [1000, 1030]}
def split_seeds(seed_config):
    """
    Create deterministic seed groups for configured data splits.

    Expands three named seed intervals into concrete integer sequences. The
    groups correspond to development, validation, and testing split labels and
    preserve Python range semantics, where the lower bound is included and the
    upper bound is excluded.

    :param seed_config: Mapping containing the required split labels and their
        two-value interval bounds.
    :type seed_config: dict[str, list[int] | tuple[int, int]]
    :raises ValueError: If any required split label is missing, or if any
        interval does not contain exactly two values.
    :return: Mapping from each required split label to the list of integer seeds
        produced from its configured interval.
    :rtype: dict[str, list[int]]
    """  # Docstring generated by Junie LLM

    if not "dev" in seed_config or not "val" in seed_config or not "test" in seed_config:
        raise ValueError("seed_config must have values for keys 'dev', 'val', and 'test'.")

    dev_range = seed_config["dev"]
    val_range = seed_config["val"]
    test_range = seed_config["test"]

    if len(dev_range) != 2 or len(val_range) != 2 or len(test_range) != 2:
        raise ValueError("seed_config keys must be exactly [start, stop].")

    return {
        "dev": list(range(dev_range[0], dev_range[1])),
        "val": list(range(val_range[0], val_range[1])),
        "test": list(range(test_range[0], test_range[1]))
    }


def concat_clips(clips):
    V = [clip["V"] for clip in clips]
    Y = [clip["Y"] for clip in clips]
    bounds = []

    start = 0
    for clip in clips:
        length = clip["V"].shape[1]
        bounds.append((start, start + length - 1))
        start = start + length

    shapesF = [v.shape[0] for v in V]
    if not np.all(np.asarray(shapesF) == shapesF[0]):
        raise ValueError("Clips disagree in shape of V")

    V = np.concatenate(V, axis=1)
    Y = np.concatenate(Y, axis=1)

    return {
        "V": V,  # (F, sum T_i)
        "Y": Y,  # (3, sum T_i)
        "bounds": bounds  # (start, stop)
    }
